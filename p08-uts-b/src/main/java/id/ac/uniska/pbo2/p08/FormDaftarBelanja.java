    private void tambahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahButtonActionPerformed
        // TODO add your handling code here:
        
String nama = namaField.getText().trim();
String hargaText = hargaField.getText().trim();

// Validasi nama barang
if (nama.isEmpty()) {
    pesanLabel.setText("Nama barang wajib diisi");
    namaField.requestFocus();
    return;
}

// Validasi barang duplikat
if (model.sudahAda(nama)) {
    pesanLabel.setText("Barang " + nama + " sudah ada di daftar");
    namaField.requestFocus();
    return;
}

// Validasi harga kosong dan bukan angka
if (!hargaText.matches("[0-9]+")) {
    pesanLabel.setText("Harga harus angka 1 sampai 10000000");
    hargaField.requestFocus();
    return;
}

long harga;

try {
    harga = Long.parseLong(hargaText);
} catch (NumberFormatException e) {
    pesanLabel.setText("Harga harus angka 1 sampai 10000000");
    hargaField.requestFocus();
    return;
}

// Validasi batas harga
if (harga < 1 || harga > 10000000) {
    pesanLabel.setText("Harga harus angka 1 sampai 10000000");
    hargaField.requestFocus();
    return;
}

// Mengambil kategori
Barang.Kategori kategori;

switch (kategoriCombo.getSelectedItem().toString()) {
    case "Alat Tulis":
        kategori = Barang.Kategori.ALAT_TULIS;
        break;
    case "Makanan":
        kategori = Barang.Kategori.MAKANAN;
        break;
    case "Minuman":
        kategori = Barang.Kategori.MINUMAN;
        break;
    default:
        kategori = Barang.Kategori.LAINNYA;
        break;
}

// Mengambil jumlah
int jumlah = (Integer) jumlahSpinner.getValue();

// Membuat objek barang
Barang barang = new Barang(nama, kategori, harga, jumlah);

// Memasukkan barang ke tabel
model.tambahBarang(barang);

// Memperbarui ringkasan
perbaruiRingkasan();

// Mengosongkan form setelah berhasil
namaField.setText("");
hargaField.setText("");
kategoriCombo.setSelectedIndex(0);
jumlahSpinner.setValue(1);

// Menghapus pesan kesalahan
pesanLabel.setText("");

namaField.requestFocus();

    }//GEN-LAST:event_tambahButtonActionPerformed

